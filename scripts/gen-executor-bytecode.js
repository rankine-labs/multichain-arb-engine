// ============================================================================
// Copies ArbExecutor's compiled runtime code into the bot, for free
// pre-trade simulation (src/execution/simulator.ts).
//
//   cd contracts && forge build && cd .. && node scripts/gen-executor-bytecode.js
//   node scripts/gen-executor-bytecode.js --check   (CI: fail if out of date)
//
// Re-run after ANY change to contracts/src/ArbExecutor.sol, or the bot would
// simulate an old version of the contract. CI enforces this.
// ============================================================================
const fs = require('fs');
const path = require('path');

const artifact = path.join(__dirname, '..', 'contracts', 'out', 'ArbExecutor.sol', 'ArbExecutor.json');
const target = path.join(__dirname, '..', 'src', 'execution', 'arbExecutorBytecode.ts');

const code = JSON.parse(fs.readFileSync(artifact, 'utf8')).deployedBytecode.object;
const out = `// GENERATED by scripts/gen-executor-bytecode.js from contracts/out (forge build).
// Do not edit by hand. Runtime code of ArbExecutor, used only to SIMULATE
// trades via eth_call state overrides. \`owner\` (storage slot 8) is unset here,
// which is fine: simulation never calls owner-only functions.
export const ARB_EXECUTOR_RUNTIME_CODE =
  '${code}';

// Storage slots (solc --storage-layout): \`executor\`, the \`flashPools\`
// allowlist mapping, and the Uniswap V4 settings (\`v4PoolManager\`, \`weth\`).
// The simulator overrides these.
export const EXECUTOR_STORAGE_SLOT = 0;
export const FLASH_POOLS_STORAGE_SLOT = 1;
export const V4_POOL_MANAGER_STORAGE_SLOT = 6;
export const WETH_STORAGE_SLOT = 7;
`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== out) {
    console.error('src/execution/arbExecutorBytecode.ts is out of date. Run: node scripts/gen-executor-bytecode.js');
    process.exit(1);
  }
  console.log('arbExecutorBytecode.ts matches the compiled contract');
} else {
  fs.writeFileSync(target, out);
  console.log('wrote', path.relative(process.cwd(), target), `(${(code.length - 2) / 2} bytes)`);
}
