#!/usr/bin/env node
// ============================================================================
// Build the compiled code that copy 2's replay (sim/src/copy2/replay.rs) and
// its offline anvil test (sim/tests/copy2_replay_anvil.rs) use.
//
// Plain English:
//   1. Compiles sim/src/copy2/ReplayHelper.sol (the pretend trader + the
//      stand-in coin used inside replays) with solc 0.8.26 and writes their
//      RUNTIME code to sim/src/copy2/replay_helper.hex and stub_token.hex.
//      replay.rs embeds those two files, so the sidecar needs no compiler.
//   2. Compiles the test helpers (sim/tests/fixtures/copy2/TestHelpers.sol:
//      test coin, random trader, PancakeSwap deployer stand-in, V4 trader)
//      and copies the REAL pool contracts' deploy code from their npm
//      packages (Uniswap V3 factory 1.0.1, PancakeSwap V3 pool 1.0.2,
//      Algebra Integral core 1.2.10 + base plugin 1.2.4, Uniswap V4
//      PoolManager 1.0.2) into sim/tests/fixtures/copy2/artifacts.json,
//      so the Rust test can deploy them on anvil without node or npm.
//
// Usage (only needed when the .sol files change):
//   node sim/tools/copy2/build.js <node_modules dir with solc + those packages>
//   e.g. node sim/tools/copy2/build.js /home/claude/event-copy-test/node_modules
// ============================================================================
const fs = require('fs');
const path = require('path');

const nm = process.argv[2];
if (!nm) {
  console.error('usage: build.js <node_modules dir>');
  process.exit(1);
}
const req = (p) => require(path.join(nm, p));
const solc = req('solc');
const SIM = path.resolve(__dirname, '..', '..');

// Compile one Solidity file; returns { ContractName: { bytecode, runtime } }.
function compile(file) {
  const input = {
    language: 'Solidity',
    sources: { [path.basename(file)]: { content: fs.readFileSync(file, 'utf8') } },
    settings: {
      optimizer: { enabled: true, runs: 200 },
      evmVersion: 'cancun',
      outputSelection: { '*': { '*': ['evm.bytecode.object', 'evm.deployedBytecode.object'] } },
    },
  };
  const out = JSON.parse(solc.compile(JSON.stringify(input)));
  for (const e of out.errors || []) if (e.severity === 'error') throw new Error(e.formattedMessage);
  const res = {};
  for (const [name, c] of Object.entries(out.contracts[path.basename(file)])) {
    res[name] = { bytecode: c.evm.bytecode.object, runtime: c.evm.deployedBytecode.object };
  }
  return res;
}

console.log('solc', solc.version());

// 1. Replay helpers -> runtime code embedded by replay.rs.
const rh = compile(path.join(SIM, 'src/copy2/ReplayHelper.sol'));
fs.writeFileSync(path.join(SIM, 'src/copy2/replay_helper.hex'), rh.ReplayHelper.runtime + '\n');
fs.writeFileSync(path.join(SIM, 'src/copy2/stub_token.hex'), rh.StubToken.runtime + '\n');

// 2. Test artifacts (deploy code).
const th = compile(path.join(SIM, 'tests/fixtures/copy2/TestHelpers.sol'));
const bc = (x) => (typeof x === 'string' ? x : x.object).replace(/^0x/, '');
const A = (p) => req('@cryptoalgebra/' + p);
const artifacts = {
  _note: 'Deploy code for the copy-2 replay anvil test. Generated by sim/tools/copy2/build.js; do not edit.',
  Token: th.Token.bytecode,
  Trader: th.Trader.bytecode,
  PancakeDeployer: th.PancakeDeployer.bytecode,
  V4Trader: th.V4Trader.bytecode,
  UniswapV3Factory: bc(req('@uniswap/v3-core/artifacts/contracts/UniswapV3Factory.sol/UniswapV3Factory.json').bytecode),
  PancakeV3Pool: bc(req('@pancakeswap/v3-core/artifacts/contracts/PancakeV3Pool.sol/PancakeV3Pool.json').bytecode),
  AlgebraFactory: bc(A('integral-core/artifacts/contracts/AlgebraFactory.sol/AlgebraFactory.json').bytecode),
  AlgebraPoolDeployer: bc(A('integral-core/artifacts/contracts/AlgebraPoolDeployer.sol/AlgebraPoolDeployer.json').bytecode),
  AlgebraVaultFactoryStub: bc(A('integral-core/artifacts/contracts/AlgebraVaultFactoryStub.sol/AlgebraVaultFactoryStub.json').bytecode),
  BasePluginV1Factory: bc(A('integral-base-plugin/artifacts/contracts/BasePluginV1Factory.sol/BasePluginV1Factory.json').bytecode),
  PoolManager: bc(req('@uniswap/v4-core/out/PoolManager.sol/PoolManager.json').bytecode),
};
fs.writeFileSync(path.join(SIM, 'tests/fixtures/copy2/artifacts.json'), JSON.stringify(artifacts, null, 1) + '\n');
console.log('wrote replay_helper.hex, stub_token.hex, tests/fixtures/copy2/artifacts.json');
